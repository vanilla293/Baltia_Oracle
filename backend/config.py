# Всё в try/except: сбой 3D-слоя даёт None + честный note, разбор не падает.

_lock = threading.RLock()
_user_cfg: dict = {}

# ── ПУЛ АККАУНТОВ DeepSeek ─────────────────────────────────────────────
# Несколько ключей-аккаунтов, между которыми раскидывается нагрузка (round-
# robin) и на которые бот переключается, если один упёрся в лимит (429) или
# кончился баланс (402). Это позволяет стабильно работать «на два аккаунта
# разом». Персональный ключ инструмента (INSTRUMENT_KEYS) имеет приоритет над
# пулом — если он задан, инструмент идёт на него.
_pool_rr = 0                       # индекс round-robin по пулу
_key_health: dict[str, float] = {}  # ключ -> «здоров снова после» (ts)


def _load_user_cfg() -> dict:
    global _user_cfg
    with _lock:
        if USER_CFG_PATH.exists():
            try:
                raw = USER_CFG_PATH.read_text(encoding="utf-8")
                if not raw.strip():
                    # пустой файл (обрыв неатомарной записи старых версий) — это «настроек нет», не авария:
                    # стартуем с пустыми ключами, файл при первой записи перезапишется атомарно
                    loaded = {}
                else:
                    loaded = json.loads(raw)
                if not isinstance(loaded, dict):
                    raise ValueError("configuration must be a JSON object")
            except (OSError, ValueError) as exc:
                # Do not silently replace a damaged credentials file with defaults.
                raise RuntimeError("Не удалось прочитать config_user.json; исходный файл сохранён") from exc
            _user_cfg = loaded
        else:
            _user_cfg = {}
        return dict(_user_cfg)


def _save_user_cfg(values: dict | None = None) -> None:
    with _lock:
        tmp = USER_CFG_PATH.with_suffix(".tmp")
        tmp.write_text(json.dumps(_user_cfg if values is None else values, ensure_ascii=False, indent=2),
                       encoding="utf-8")
        os.replace(tmp, USER_CFG_PATH)
        try:
            os.chmod(USER_CFG_PATH, 0o600)
        except Exception:
            pass


_load_user_cfg()


def get(name: str, default: str = "") -> str:
    with _lock:
        if name in _user_cfg and _user_cfg[name] not in (None, ""):
            return str(_user_cfg[name])
    return os.getenv(name, default)


def get_int(name: str, default: int) -> int:
    try:
        return int(float(get(name, str(default))))
    except (ValueError, TypeError, OverflowError):
        return default


def get_float(name: str, default: float) -> float:
    try:
        value = float(get(name, str(default)))
        return value if math.isfinite(value) else default
    except (ValueError, TypeError):
        return default


def get_bool(name: str, default: bool) -> bool:
    v = get(name, "1" if default else "0").strip().lower()
    return v in ("1", "true", "yes", "on", "да")


def set_many(updates: dict) -> None:
    """Записать несколько ключей в config_user.json и обновить кэш модулей."""
    global _user_cfg
    with _lock:
        next_cfg = dict(_user_cfg)
        for k, v in updates.items():
            if v is None or v == "":
                next_cfg.pop(k, None)
            else:
                next_cfg[k] = v
        # Commit to disk before publishing the new configuration to readers.
        _save_user_cfg(next_cfg)
        _user_cfg = next_cfg
        _refresh()


def public_snapshot() -> dict:
    """Безопасный для отдачи в UI снимок (без полных секретов)."""
    def mask(s: str) -> str:
        if not s:
            return ""
        return s[:4] + "…" + s[-3:] if len(s) > 10 else "•••"
    return {
        "app_name": APP_NAME,
        "codename": APP_CODENAME,
        "version": APP_VERSION,
        "model": DEEPSEEK_MODEL,
        "model_fast": DEEPSEEK_MODEL_FAST,
        "base_url": DEEPSEEK_BASE_URL,
        "has_tinkoff_token": bool(TINKOFF_TOKEN),
        "tinkoff_token_mask": mask(TINKOFF_TOKEN),
        "news_days": NEWS_DAYS,
        "instrument_keys": {k: mask(v) for k, v in INSTRUMENT_KEYS.items()},
        "deepseek_accounts": len(deepseek_keys()),
        "deepseek_accounts_mask": [mask(k) for k in deepseek_keys()],
    }


def deepseek_keys() -> list[str]:
    """Пул ключей-аккаунтов DeepSeek (для работы на несколько аккаунтов разом)."""
    with _lock:
        return [k for k in _user_cfg.get("DEEPSEEK_KEYS", []) if k]


def set_deepseek_keys(keys: list[str]) -> None:
    """Задать пул аккаунтов. Чистит пробелы/дубли, отсекает явно не-ключи."""
    clean, seen = [], set()
    for k in (keys or []):
        k = "".join(ch for ch in str(k or "") if ord(ch) > 32)   # выкидываем пробелы/переносы
        if k and k.isascii() and len(k) <= 512 and k not in seen:
            seen.add(k)
            clean.append(k)
    set_many({"DEEPSEEK_KEYS": clean or None})


def mark_key_unhealthy(key: str, seconds: float = 60.0) -> None:
    """Пометить аккаунт временно нездоровым (лимит/баланс) — не выбираем его seconds."""
    if key:
        with _lock:
            _key_health[key] = time.time() + max(5.0, seconds)


def pick_pool_key(exclude: str | None = None) -> str:
    """Следующий здоровый ключ пула (round-robin). exclude — не брать этот."""
    global _pool_rr
    pool = deepseek_keys()
    if not pool:
        return ""
    now = time.time()
    with _lock:
        healthy = [k for k in pool if k != exclude and _key_health.get(k, 0) <= now]
        cands = healthy or [k for k in pool if k != exclude] or pool
        _pool_rr = (_pool_rr + 1) % len(cands)
        return cands[_pool_rr]


def failover_key(bad_key: str) -> str:
    """Дать ДРУГОЙ аккаунт вместо упавшего. Персональные ключи инструментов НЕ
    подменяем (они заданы намеренно) — только ключи из пула аккаунтов."""
    if not bad_key or bad_key not in deepseek_keys():
        return ""
    mark_key_unhealthy(bad_key, 60.0)
    alt = pick_pool_key(exclude=bad_key)
    return alt if alt and alt != bad_key else ""


def key_for(ticker: str) -> str:
    """Ключ DeepSeek для инструмента: сперва ЛИЧНЫЙ ключ объекта (если задан),
    иначе — следующий аккаунт из пула (round-robin, раскидывает пакет по
    аккаунтам). Так бот работает на несколько аккаунтов разом."""
    personal = INSTRUMENT_KEYS.get((ticker or "").upper().strip(), "")
    return personal or pick_pool_key()


def has_key_for(ticker: str) -> bool:
    personal = INSTRUMENT_KEYS.get((ticker or "").upper().strip(), "")
    return bool(personal) or bool(deepseek_keys())


def set_instrument_key(ticker: str, key: str | None) -> None:
    """Задать/снять персональный ключ DeepSeek для инструмента."""
    ticker = (ticker or "").upper().strip()
    if not ticker:
        return
    with _lock:
        m = dict(_user_cfg.get("INSTRUMENT_KEYS", {}))
        if key:
            m[ticker] = key
        else:
            m.pop(ticker, None)
        set_many({"INSTRUMENT_KEYS": m})


def wipe_keys() -> None:
    """Стереть ВСЕ ключи и токены: пул аккаунтов DeepSeek, ключи по инструментам,
    токен Tinkoff, токен и чат Telegram. Используется для полностью чистого старта."""
    with _lock:
        set_many({k: None for k in ("DEEPSEEK_API_KEY", "DEEPSEEK_KEYS", "TINKOFF_TOKEN", "INSTRUMENT_KEYS",
                                   "TG_BOT_TOKEN", "TG_CHAT_ID")})
        _key_health.clear()


