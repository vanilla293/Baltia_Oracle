FREE_PILOT_DEFAULTS = {
    "PYTHIA_ENTRY_TIMEOUT_SEC": 1200, "PYTHIA_PROFIT_TIMEOUT_SEC": 1200, "PYTHIA_SILENT_RETRY_SEC": 120,
    "PYTHIA_ENTRY_SILENT_MAX": 2, "PYTHIA_ENTRY_FRESH_SEC": 1200, "PYTHIA_ENTRY_DRIFT_PCT": 1.0,
    "PYTHIA_WAIT_REVIEW_SEC": 1800, "PYTHIA_COUNCIL_MAX_SEC": 7200,
}


def pin_free_pilot_defaults(setter=None) -> dict:
    """Поставить умолчания 5.4.2 в живые значения модуля (только для тестов и стенда). setter(name, value) —
    например monkeypatch.setattr-обёртка; без него — прямое присваивание. Возвращает прежние значения."""
    g = globals()
    old = {k: g.get(k) for k in FREE_PILOT_DEFAULTS}
    for k, v in FREE_PILOT_DEFAULTS.items():
        if setter:
            setter(k, v)
        else:
            g[k] = v
    return old


def _refresh() -> None:
    g = globals()

    # — DeepSeek — (общего ключа НЕТ: только ключи по инструментам)
    g["DEEPSEEK_API_KEY"]  = ""
    g["DEEPSEEK_BASE_URL"] = get("DEEPSEEK_BASE_URL", "https://api.deepseek.com")
    # «Умная» модель — pro с thinking. Тупая (быстрая) — flash, только под форматирование.
    g["DEEPSEEK_MODEL"]      = get("DEEPSEEK_MODEL", "deepseek-v4-pro")
    # deepseek-flash — официальное имя V4.1-Flash с 10.09.2026 (старое deepseek-v4-flash выведено и пока
    # молча маршрутизируется туда же); ai._is_v4 узнаёт оба
    g["DEEPSEEK_MODEL_FAST"] = get("DEEPSEEK_MODEL_FAST", "deepseek-flash")

    # — Tinkoff —
    tok = get("TINKOFF_TOKEN", "")
    if not tok:
        for alt in ("TINKOFF_API_TOKEN", "tinkoff_token", "tinkoffToken"):
            tok = get(alt, "")
            if tok:
                break
    g["TINKOFF_TOKEN"] = tok
    g["TINKOFF_PRICE_CACHE_SEC"] = max(0.5, min(get_float("TINKOFF_PRICE_CACHE_SEC", 2.0), 30.0))

    # — Сервер —
    g["HOST"] = get("HOST", "0.0.0.0")
    g["PORT"] = get_int("PORT", 8799)

    # — Новости —
    g["NEWS_DAYS"] = max(1, min(get_int("NEWS_DAYS", 2), 30))    # глубина выгрузки новостей
    g["NEWS_CACHE_SEC"] = get_int("NEWS_CACHE_SEC", 300)

    # — ИИ-параметры конвейера —
    # ПОТОЛОК ТОКЕНОВ (расследование 24.09.2026 по документации DeepSeek): если max_tokens НЕ слать,
    #   сервер сам ставит потолок 64K на ответ ВМЕСТЕ с размышлением (8K без размышления, 128K только
    #   при effort=max) — 32 000 токенов ответа при глубоком размышлении туда не влезают: content
    #   приходит пустым или обрезанным (finish_reason=length). Поэтому шлём явно максимум модели
    #   393 216 (384K): модель всё равно останавливается сама, потолок — лишь техническая граница API.
    #   0 — не слать (умолчание сервера), число — своё (1000…393216).
    # ГЛУБИНА РАССУЖДЕНИЯ (effort): режима «auto» у DeepSeek нет — есть none/low/high/max, умолчание
    #   сервера high. Воля владельца: ничего не навязывать — пусто = не шлём = умолчание API (high),
    #   ровно как в первой ПИФИИ 4.5.4 (она слала high явно). Переменные — только для экспериментов.
    _mt = get_int("AI_MAX_TOKENS", 393_216)
    g["AI_MAX_TOKENS"] = 0 if _mt <= 0 else max(1000, min(_mt, 393_216))
    g["AI_REASONING_EFFORT"] = get("AI_REASONING_EFFORT", "")
    g["AI_REASONING_EFFORT_MAX"] = get("AI_REASONING_EFFORT_MAX", "")
    g["AI_THINKING"] = get_bool("AI_THINKING", True)
    # распределитель новостей теперь тоже УМНЫЙ (думает перед отбором/тегами/фоном)
    g["NEWS_THINKING"] = get_bool("NEWS_THINKING", True)

    # — Кэш досье/прогнозов —
    g["ANALYSIS_TTL_SEC"] = get_int("ANALYSIS_TTL_SEC", 1800)

    # — Чистый старт (так задумано): ключи и кэш живут ТОЛЬКО пока программа
    #   работает. При выключении сервера И при каждом запуске стираются архив
    #   разборов, чат И все ключи (DeepSeek по инструментам + токен Tinkoff) —
    #   на диске после выхода ничего не остаётся. Стирание на запуске страхует
    #   случай, когда программу убили жёстко и хук выключения не успел.
    #   Кто хочет сохранять между сессиями — ставит эти флаги в 0.
    # v5: ключи и база ЖИВУТ между запусками (новости копятся 3 дня, журнал
    #     сделок и советы переживают перезапуск). Стереть ключи — кнопкой в панели.
    g["RESET_ON_START"] = get_bool("RESET_ON_START", False)
    g["WIPE_KEYS_ON_START"] = get_bool("WIPE_KEYS_ON_START", False)
    g["WIPE_ON_EXIT"] = get_bool("WIPE_ON_EXIT", False)

    # — v5 «СОВЕТ» —
    g["PYTHIA_V5_DAYS"] = max(1, min(get_int("PYTHIA_V5_DAYS", 3), 14))      # окно новостей
    g["PYTHIA_WATCH_SEC"] = max(120, get_int("PYTHIA_WATCH_SEC", 900))       # период дозора
    g["PYTHIA_WATCH_SERIOUS"] = max(1, min(get_int("PYTHIA_WATCH_SERIOUS", 75), 100))
    g["PYTHIA_FLASH_PAR"] = max(1, min(get_int("PYTHIA_FLASH_PAR", 6), 16))  # параллель flash
    # v5.1 «ВСЁ, НО В РАЗУМНЫХ ПРЕДЕЛАХ»: DeepSeek V4 держит окно 1 048 576 токенов, но
    # уже на половине окна ответ заметно хуже, чем на чистом листе (наблюдение владельца).
    # Поэтому входы не режутся ножницами, а СЖИМАЮТСЯ FLASH без потери нитей:
    #   PYTHIA_CTX_LIMIT  — порог сжатия ОДНОГО блока (60 000 симв. ≈ 20–25 тыс. токенов
    #                       кириллицы): выше — FLASH ужимает блок по частям (compress.shrink);
    #   PYTHIA_PROMPT_SOFT — общий предел user-текста одного вызова (300 000 симв. ≈ 100–120 тыс.
    #                       токенов): выше — compress.fit ужимает самые большие блоки;
    #   PYTHIA_PROMPT_CAP — жёсткий потолок (голова+хвост), только авария.
    # 5.4.1 (владелец: «раньше был трезвее»): пределы ×3 из 5.3.3 давали промпты по 400–600 тыс. симв. — модель
    # тонула в слоях и мялась; возвращены 60 000 / 300 000 / 450 000 (как в 5.1–5.3.2): блок выше 60 000 симв.
    # ужимается FLASH без потери нитей, промпт выше 300 000 — самые большие блоки; ножниц по-прежнему нет.
    g["PYTHIA_CTX_LIMIT"] = max(2000, get_int("PYTHIA_CTX_LIMIT", 60_000))
    g["PYTHIA_PROMPT_SOFT"] = max(10_000, get_int("PYTHIA_PROMPT_SOFT", 300_000))
    g["PYTHIA_PROMPT_CAP"] = max(20_000, get_int("PYTHIA_PROMPT_CAP", 450_000))
    g["PYTHIA_GNEWS"] = get_bool("PYTHIA_GNEWS", True)     # Google News по инструментам (совет + миссия)
    g["PYTHIA_SCAN_MIN"] = max(5, min(get_int("PYTHIA_SCAN_MIN", 480), 480))   # сканер стакана миссии, мин
    g["PYTHIA_REVIEW_SEC"] = max(300, get_int("PYTHIA_REVIEW_SEC", 1800))    # перепроверка миссии
    # РИТМ МИССИИ (v5.1h): дежурный PRO думает и решает раз в PYTHIA_REVIEW_SEC (купить / продать /
    # ждать / закрыть / звать совет). Внеплановую перепроверку поднимают только события:
    #   PYTHIA_SHOCK_PCT   — резкий ход цены (в %, за окно PYTHIA_SHOCK_WIN_SEC), 0 — выключить;
    #   PYTHIA_EVENT_COOL_SEC — внеплановые перепроверки (резкий ход, серьёзная новость, поводы
    #                        пилота) не чаще раза в N с;
    #   PYTHIA_AFTER_CLOSE_SEC — после закрытия позиции (стоп/тейк/решение) остыть N с, потом PRO
    #                        решает заново (0 — ждать плановой перепроверки);
    #   PYTHIA_QUIET_SEC   — тишина после входа: события в первые N с не приближают перепроверку
    #                        (повод дойдёт до плановой), трос защищает;
    #   PYTHIA_FLIP_QUIET_SEC — вердикт другой стороны при позиции моложе N с не переворачивает её
    #                        (0 — выключить);
    #   PYTHIA_COUNCIL_GAP_SEC — полный совет (три кресла) по автоматическим поводам (НОВЫЙ_АНАЛИЗ
    #                        от PRO, серьёзная новость без пилота) не чаще раза в N с.
    g["PYTHIA_SHOCK_PCT"] = max(0.0, get_float("PYTHIA_SHOCK_PCT", 1.0))
    g["PYTHIA_SHOCK_WIN_SEC"] = max(60, get_int("PYTHIA_SHOCK_WIN_SEC", 600))
    g["PYTHIA_EVENT_COOL_SEC"] = max(0, get_int("PYTHIA_EVENT_COOL_SEC", 900))
    g["PYTHIA_AFTER_CLOSE_SEC"] = max(0, get_int("PYTHIA_AFTER_CLOSE_SEC", 900))
    g["PYTHIA_QUIET_SEC"] = max(0, get_int("PYTHIA_QUIET_SEC", 900))
    g["PYTHIA_FLIP_QUIET_SEC"] = max(0, get_int("PYTHIA_FLIP_QUIET_SEC", 1200))
    g["PYTHIA_COUNCIL_GAP_SEC"] = max(0, get_int("PYTHIA_COUNCIL_GAP_SEC", 1800))
    # ── v5.2 «ВЕСЬ СЧЁТ» ──
    #   PYTHIA_ADOPT_ACCOUNT — всё, что лежит на счёте по инструменту миссии, — позиция бота
    #       (докупил владелец → позиция выросла, продал → уменьшилась; ИИ не думает «сколько
    #       куплено», он даёт приказ купить/продать, размер — максимум, что даёт биржа);
    #       0 — старая изоляция «ручных лотов» (бот ведёт только своё).
    #   PYTHIA_SOFT_STOP — мягкий стоп: цена коснулась уровня «идея мертва» → FLASH за секунды
    #       получает максимум данных и решает: слить сейчас или ждать и передать задачу Совету;
    #       0 — жёсткий стоп как раньше (закрыть сразу).
    #   PYTHIA_HARD_STOP_PCT — аварийный биржевой трос: на N % дальше уровня триггера; лежит на
    #       сервере биржи и срабатывает, даже если бот мёртв; за ним код закрывает без вопросов.
    #   PYTHIA_SOFT_STOP_GRACE_SEC — после «ждать» FLASH не спрашивают чаще N с (если он не назвал
    #       свой срок); PYTHIA_SOFT_STOP_MAX_HOLDS — столько раз подряд можно «ждать» за
    #       триггером, потом код закрывает (0 — без предела).
    #   PYTHIA_TOPUP_MAX — после входа пилот ещё N раз добирает лоты, если биржа даёт (округление,
    #       освободившаяся маржа) — «на максималку».
    #   PYTHIA_SCOUT — разведка данных FLASH перед советом/миссией (индексный фьючерс, соседи, курсы);
    #       PYTHIA_SCOUT_MAX — не больше N запросов за раз.
    #   PYTHIA_PARTNERS — связанные бумаги (correlate: ρ по дневным доходностям с соседями по сектору
    #       и макро-фьючерсами) в данных совета, перепроверки, троса, чата; 0 — выключить.
    #   PYTHIA_CHAT_MODEL — модель чата панели по умолчанию: pro | flash.
    g["PYTHIA_ADOPT_ACCOUNT"] = get_bool("PYTHIA_ADOPT_ACCOUNT", True)
    g["PYTHIA_SOFT_STOP"] = get_bool("PYTHIA_SOFT_STOP", True)
    g["PYTHIA_HARD_STOP_PCT"] = max(0.1, min(get_float("PYTHIA_HARD_STOP_PCT", 1.5), 20.0))
    g["PYTHIA_SOFT_STOP_GRACE_SEC"] = max(30, get_int("PYTHIA_SOFT_STOP_GRACE_SEC", 180))
    g["PYTHIA_SOFT_STOP_MAX_HOLDS"] = max(0, get_int("PYTHIA_SOFT_STOP_MAX_HOLDS", 3))
