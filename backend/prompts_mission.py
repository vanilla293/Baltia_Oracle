# ── блок «ПРОКОЛ СКАНЕРА» (v5.3 W3): прокол как повод для ИИ — факты и числа, толкование отдельно ──
# v5.4.3: у всех ролей одна и та же оговорка — не голое сомнение «или ложный прокол», а критерий (PUNCTURE_FALSE)
PUNCTURE_FALSE = "(ложный — если агрессор ленты и тяга против прокола: реши по картине)"
PUNCTURE_ROLES = {
    "вход": f"прокол в сторону плана — возможный момент входа {PUNCTURE_FALSE}",
    "предупреждение": f"прокол против плана — возможный довод против входа {PUNCTURE_FALSE}",
    "угроза": f"прокол против нас — возможная угроза: цена может быстро пройти полосу к тросу {PUNCTURE_FALSE}",
    "подтверждение": f"прокол за нас — возможное подтверждение: путь наименьшего сопротивления в нашу сторону {PUNCTURE_FALSE}",
    "вне рынка": ("прокол вне рынка — возможный момент входа в сторону прокола; засада за полосой опоздает "   # v5.4.2
                  f"{PUNCTURE_FALSE}"),
}
PUNCTURE_SCHOOL = ("Как читают: устойчивый вакуум — коридор, где цена пройдёт быстро; сигнал упреждающий, срабатывает "
                   "с задержкой; «прокол» — словарь Майи, не приказ.")


def _pct(x) -> str:
    try:
        return f"{float(x) * 100:.0f} %"
    except (TypeError, ValueError):
        return "н/д"


def puncture_block(side: str, persistence, p_lo, p_hi, *, role: str, our_side: str | None = None,
                   in_pos: bool = False, price=None, depth=None, ticks=None, consensus: dict | None = None,
                   hawkes_n=None, tension: str | None = None) -> str:
    """Блок «ПРОКОЛ СКАНЕРА» для ситуации PRO/FLASH: сторона, стойкость, полоса, тяга, серия тиков, агрессор,
    Хоукс, натяжение — числа сканера как есть; «что это значит для нас» — роль по позиции/плану (PUNCTURE_ROLES);
    толкование школы отдельной фразой. Нет данных → поля опускаются, ничего не выдумывается."""
    L = [f"ПРОКОЛ СКАНЕРА: сторона {str(side or '?').upper()}, стойкость {_pct(persistence)}"
         + (f" (полосу держат {int(ticks)} тиков)" if ticks else "")
         + f", полоса {_fmt(p_lo)}–{_fmt(p_hi)}"]
    try:
        if price and float(price) > 0 and p_lo is not None:
            edge = float(p_lo) if side == "вверх" else float(p_hi)
            L[0] += f" (цена {float(price):g}, до полосы {(edge / float(price) - 1) * 100:+.2f} %)"
    except (TypeError, ValueError):
        pass
    if depth is not None:
        L[0] += f", глубина вакуума {depth}"
    c = consensus or {}
    if c:
        st = c.get("streak") or {}
        s = (f"тяга за окно: вверх {_pct(c.get('up_share'))} / вниз {_pct(c.get('dn_share'))} тиков"
             + (f" ({c.get('word')})" if c.get("word") else ""))
        if st:
            s += f"; последние {st.get('win')} тиков: вверх {st.get('up')} / вниз {st.get('dn')}"
        ar = c.get("aggressor_mean")
        if ar is not None:
            try:
                ar = float(ar)
                s += f"; агрессор ленты {ar:.2f} ({'покупатель' if ar > 0.55 else 'продавец' if ar < 0.45 else 'паритет'}"
                s += (", с тягой согласен" if c.get("agree") is True else ", против тяги" if c.get("agree") is False else "") + ")"
            except (TypeError, ValueError):
                pass
        L.append(s)
    extra = []
    if hawkes_n is not None:
        extra.append(f"Хоукс по ленте n={hawkes_n}")
    if tension:
        extra.append(str(tension))
    if extra:
        L.append("; ".join(extra))
    who = (f"мы в позиции {our_side}" if in_pos else f"мы вне рынка, план/приказ {our_side}") if our_side else "мы вне рынка без плана"
    L.append(f"Что это значит для нас: {who} — {PUNCTURE_ROLES.get(role, role or 'сторона не важна')}.")
    L.append(PUNCTURE_SCHOOL)
    return "\n".join(L)


def _fmt(x) -> str:
    try:
        v = float(x)
        return f"{v:.10g}"
    except (TypeError, ValueError):
        return "н/д"


