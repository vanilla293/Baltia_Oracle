def _fresh_min() -> int:
    """Сколько минут решение PRO бьётся без второго вопроса у двери (PYTHIA_ENTRY_FRESH_SEC) — промпт говорит правду."""
    return int(float(getattr(config, "PYTHIA_ENTRY_FRESH_SEC", 1200) or 0) // 60)


