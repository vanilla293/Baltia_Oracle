def _context_blocks(ctx: dict) -> list[str]:
    """Общий хвост контекста для думающих стадий: все слои целиком."""
    parts: list[str] = []
    for key, title in _CONTEXT_ORDER:
        parts += _block(title, ctx.get(key, ""))
    return parts


def _head(ticker: str, name: str, ctx: dict, play: str) -> list[str]:
    head = [f"ОБЪЕКТ: {ticker} — {name}. Класс: {ctx.get('asset_class') or '?'}.",
            f"ВРЕМЯ: {ctx.get('time_msk', '?')}. Цена сейчас: {ctx.get('price')}."]
    if ctx.get("market"):                    # рыночные часы: закрыто → вход только с открытия
        head.append(f"РЫНОК: {ctx['market']}.")
    return head + [f"РЕЖИМ ИГРЫ: {play_rule(play)}.",
                   f"ПОВОД: {ctx.get('reason') or 'запуск миссии'}."]


