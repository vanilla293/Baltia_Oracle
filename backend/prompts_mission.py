def play_rule(play: str) -> str:
    return PLAY_RULE.get((play or "auto").lower(), PLAY_RULE["auto"])


def _cap() -> int:
    return int(getattr(config, "PYTHIA_PROMPT_CAP", 450_000))


def _block(title: str, text: str) -> list[str]:
    """Блок контекста как дали (пределы держит mission.py через compress.fit/shrink;
    здесь — только аварийный потолок PYTHIA_PROMPT_CAP на весь текст в `_finish`)."""
    t = (text or "").strip()
    if not t:
        return []
    return ["", f"═══ {title} ═══", t]


def _finish(parts: list[str], label: str) -> str:
    """Склейка user-текста с единственным аварийным тормозом — жёстким потолком."""
    return _clip("\n".join(parts), _cap(), label)


