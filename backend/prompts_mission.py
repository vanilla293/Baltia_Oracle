def review_options(play: str, in_pos: bool, side: str | None = None) -> str:
    """Допустимые решения дежурного PRO — действия первыми, ожидание и удержание последними (v5.4.3).
    В позиции: ЗАКРЫТЬ / ДОБРАТЬ (докупить до максимума, что даёт биржа) / ПЕРЕВЕРНУТЬ (если режим игры пускает в
    другую сторону) / НОВЫЙ_АНАЛИЗ / ДЕРЖАТЬ. Без позиции: КУПИТЬ / ПРОДАТЬ (по режиму) / НОВЫЙ_АНАЛИЗ / ЖДЁМ.
    Метки без «_СЕЙЧАС»: КУПИТЬ/ПРОДАТЬ — и вход сразу, и засада у уровня (entry_kind откат/прорыв). Канон кода
    прежний: ai_v5.review_table сводит КУПИТЬ → КУПИТЬ_СЕЙЧАС, ПРОДАТЬ → ПРОДАТЬ_СЕЙЧАС, ДЕРЖАТЬ → ЖДЁМ."""
    p = (play or "auto").lower()
    if in_pos:
        opts = ["ЗАКРЫТЬ", "ДОБРАТЬ"]
        other = "short" if (side or "long") == "long" else "long"
        if p in ("mixed", "auto") or p == other:
            opts.append("ПЕРЕВЕРНУТЬ")
        opts += ["НОВЫЙ_АНАЛИЗ", "ДЕРЖАТЬ"]
        return " | ".join(opts)
    opts = []
    if p in ("long", "mixed", "auto"):
        opts.append("КУПИТЬ")
    if p in ("short", "mixed", "auto"):
        opts.append("ПРОДАТЬ")
    opts += ["НОВЫЙ_АНАЛИЗ", "ЖДЁМ"]
    return " | ".join(opts)


