@_safe(_err)
def constellation_of(ra_deg, dec_deg, epoch=None):
    """🔵 РЕАЛЬНОЕ созвездие (одно из 88) по экваториальным координатам.

    ra_deg, dec_deg — прямое восхождение и склонение, градусы.
    epoch — эпоха равноденствия входных координат:
        None  → координаты в ICRS/GCRS (без равноденствия) — режим по умолчанию,
                ровно то, что принимает astropy.get_constellation;
        число → средний экватор и равноденствие этой эпохи (юлианский год
                вроде 2026.6 или юлианская дата).

    Внутри: прецессия (с bias) к B1875 и поиск по таблице Делпорта — как в каноне.
    Возвращает: code, name (рус.), name_lat, zodiacal, ra_b1875_deg, dec_b1875_deg.
    """
    v = _unit_from_radec(np.atleast_1d(ra_deg), np.atleast_1d(dec_deg))
    if epoch is not None:
        # из среднего экватора эпохи обратно в GCRS, затем в B1875
        v = _bias_precession_matrix(_as_jd(epoch)).T @ v
    codes, rah, decd = _lookup_b1875(_to_b1875_from_gcrs(v))
    return _describe(codes[0], {"ra_b1875_deg": float(rah[0] * 15.0),
                                "dec_b1875_deg": float(decd[0])})


def _ecl_to_b1875(lon_deg, lat_deg, jd):
    """Видимые (apparent) эклиптические λ, β даты → единичные векторы в B1875.

    Цепочка 🔵: истинная эклиптика даты → средняя (снимаем нутацию в долготе Δψ:
    для эклиптических координат это ТОЧНО λ_mean = λ_true − Δψ, плоскость
    эклиптики нутация не наклоняет) → средний экватор даты (наклон ε₀) →
    GCRS → B1875."""
    lam = np.radians(np.asarray(lon_deg, dtype=np.float64)
                     - nutation(jd)[0])          # к среднему равноденствию даты
    bet = np.radians(np.asarray(lat_deg, dtype=np.float64))
    eps = math.radians(obliquity_mean_deg(jd))
    cb = np.cos(bet)
    xe, ye, ze = cb * np.cos(lam), cb * np.sin(lam), np.sin(bet)
    ce, se = math.cos(eps), math.sin(eps)
    v_eq = np.stack([xe, ye * ce - ze * se, ye * se + ze * ce])   # экватор даты
    return _M_B1875 @ (_bias_precession_matrix(jd).T @ v_eq)


@_safe(_err)
def constellation_of_ecliptic(lon_deg, lat_deg, jd_or_year):
    """🔵 ОСНОВНОЙ ОТВЕТ «ГДЕ ТЕЛО» — реальное созвездие из 88 по видимым
    эклиптическим ДОЛГОТЕ И ШИРОТЕ.

    lon_deg, lat_deg — apparent λ и β даты (аксиома мгновенности: видимое небо
    и есть небо связи). ШИРОТУ НЕ ВЫБРАСЫВАТЬ: у Плутона β до ±17°, у Луны и
    Меркурия тоже — они реально стоят в Ките, Змееносце, Орионе.
    jd_or_year — юлианская дата или юлианский год.
    """
    jd = _as_jd(jd_or_year)
    v = _ecl_to_b1875(np.atleast_1d(lon_deg), np.atleast_1d(lat_deg), jd)
    codes, rah, decd = _lookup_b1875(v)
    return _describe(codes[0], {
        "lon_deg": float(np.atleast_1d(lon_deg)[0]),
        "lat_deg": float(np.atleast_1d(lat_deg)[0]),
        "ra_b1875_deg": float(rah[0] * 15.0), "dec_b1875_deg": float(decd[0]),
    })


def _codes_of_ecliptic(lon_arr, lat_arr, jd):
    """Векторный внутренний путь (без словарей) — для сканов и self-теста."""
    return _lookup_b1875(_ecl_to_b1875(lon_arr, lat_arr, jd))[0]


@_safe(_err)
def band_projection(lon_deg, jd_or_year):
    """🟡/🔵 ДИАГНОСТИКА, А НЕ ОТВЕТ. Что было бы, если бы широту β выбросили
    в мусор (β=0) — проекция тела на пояс эклиптики. Нужна ровно для того,
    чтобы РАСХОЖДЕНИЕ с настоящим положением было видно глазами.

    Для точек, у которых β=0 по построению (ASC, MC, узлы, Лилит), это не
    проекция, а честный ответ — они действительно лежат на эклиптике."""
    r = constellation_of_ecliptic(lon_deg, 0.0, jd_or_year)
    if "error" not in r:
        r["note"] = ("🟡 проекция на пояс при β=0 — диагностика расхождения, "
                     "не ответ на вопрос «где тело»")
    return r


@_safe(_err)
def tropical_sign(lon_deg):
    """🟡 СИМВОЛЬНАЯ СЕТКА, А НЕ НЕБО. Тридцатиградусный «знак»: 12 равных
    ломтей по 30°, отсчитанных от точки весеннего равноденствия.

    Это НЕ созвездие и НЕ положение тела. Из-за прецессии сетка уехала от
    реального неба на ~24° (drift_deg): тело с λ=130° названо «Лев», а стоит
    в Раке. Настоящий ответ даёт constellation_of_ecliptic(λ, β, jd).
    """
    lam = float(lon_deg) % 360.0
    i = int(lam // 30.0) % 12
    return {
        "index": i, "name": TROPICAL_SIGNS_RU[i], "name_lat": TROPICAL_SIGNS_LAT[i],
        "degree_in_sign": lam - 30.0 * i, "symbolic": True, "is_sky": False,
        "note": "🟡 равная 30° сетка от точки весны — язык школы, не небо",
    }


@_safe(lambda e: None)
def drift_deg(jd_or_year, zero_epoch_year=AYANAMSHA_ZERO_YEAR):
    """Расхождение тропической сетки с реальным небом в градусах (аянамша).

    🔵 Механика: берём направление точки весеннего равноденствия нулевой эпохи
    (фиксированное направление на небе) и измеряем его эклиптическую долготу на
    заданную дату по той же модели прецессии IAU 2006. Это и есть накопленная
    общая прецессия в долготе.
    🟡 Конвенция: сам нулевой год (по умолчанию 221 н.э., ~Фейган–Брэдли) —
    договорённость школы о том, «когда тропика совпадала с небом», а не
    измеряемая величина. Меняется параметром, честно называется.

    Возвращает градусы (для 2026 ≈ 25.2°) или None при сбое.
    """
    jd = _as_jd(jd_or_year)
    jd0 = _as_jd(float(zero_epoch_year))
    # точка весны нулевой эпохи в её собственном среднем экваторе = (1,0,0)
    v_gcrs = _bias_precession_matrix(jd0).T @ np.array([1.0, 0.0, 0.0])
    v_eq = _bias_precession_matrix(jd) @ v_gcrs          # средний экватор даты
    eps = math.radians(obliquity_mean_deg(jd))
    ce, se = math.cos(eps), math.sin(eps)
    x = v_eq[0]
    y = v_eq[1] * ce + v_eq[2] * se                      # поворот в эклиптику
    return math.degrees(math.atan2(y, x)) % 360.0


