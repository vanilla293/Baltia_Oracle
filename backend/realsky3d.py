def _safe(fallback):
    """Каждый слой в своей защите: сбой одного не роняет весь разбор.
    fallback(e) → что вернуть вместо исключения."""
    def deco(fn):
        @functools.wraps(fn)
        def wrap(*a, **kw):
            try:
                return fn(*a, **kw)
            except Exception as e:            # noqa: BLE001 — это и есть защита слоя
                return fallback(e)
        return wrap
    return deco


def _err(e):
    return {"error": f"{type(e).__name__}: {e}"}


