def _ecliptic_arcs(jd, step_deg=0.02):
    """Разбить эклиптику (β=0) на дуги реальных созвездий.
    Возвращает список (lon_start, lon_end, code), обход по возрастанию долготы.
    Границы уточняются делением пополам до ~1e-7°."""
    n = int(round(360.0 / step_deg))
    grid = np.arange(n, dtype=np.float64) * (360.0 / n)
    codes = _codes_of_ecliptic(grid, np.zeros(n), jd)

    def code_at(x):
        return _codes_of_ecliptic(np.array([x % 360.0]), np.zeros(1), jd)[0]

    edges = []
    for i in range(n):
        a, b = codes[i - 1], codes[i]          # i-1 = -1 закрывает круг
        if a == b:
            continue
        lo = (grid[i] - 360.0 / n)             # может быть -step на стыке
        hi = grid[i]
        for _ in range(34):                    # 0.02° / 2^34 — с большим запасом
            mid = 0.5 * (lo + hi)
            if code_at(mid) == a:
                lo = mid
            else:
                hi = mid
        edges.append(0.5 * (lo + hi) % 360.0)

    edges = sorted(set(round(e, 9) for e in edges))
    arcs = []
    for k, s in enumerate(edges):
        e = edges[(k + 1) % len(edges)]
        width = (e - s) % 360.0
        arcs.append((s, e, code_at(s + 0.5 * width)))
    return arcs


@_safe(_err)
def houses_real(jd, lat, lon, step_deg=0.02):
    """🔵 ДОМА ПО РЕАЛЬНЫМ ГРАНИЦАМ СОЗВЕЗДИЙ вдоль эклиптики.

    Они НЕРАВНЫЕ: Дева тянется ~44°, Скорпион ~7°, Змееносец ~18°, — поэтому
    асцендент проходит их рывками, а не по 30° ровно. Дом №1 — созвездие, в
    котором стоит асцендент; дальше по возрастанию долготы (порядок восхождения).

    Для каждого дома: код и имя созвездия, границы по долготе, ширина в градусах
    и сколько времени асцендент в нём проводит (часы среднего солнечного времени).

    Ключ "equal" 🟡 — прежние равные 30-градусные дома от асцендента. Отдан
    отдельно и помечен как проекция, чтобы старые потребители не рассыпались.

    На |широте| > ~66.5° часть эклиптики не восходит: время честно None + note,
    вместо выдуманного числа (NO DUMMIES).
    """
    jd = _as_jd(jd)
    asc, lst, eps = _asc_lon(jd, float(lat), float(lon))
    phi = math.radians(float(lat))
    arcs = _ecliptic_arcs(jd, step_deg)

    # дом №1 — дуга, в которой стоит асцендент
    start_i = 0
    for i, (s, e, _c) in enumerate(arcs):
        if ((asc - s) % 360.0) < ((e - s) % 360.0 or 360.0):
            start_i = i
            break

    # За полярным кругом (|φ| ≥ 90°−ε) часть эклиптики околополярна: асцендент
    # обходит её НЕ монотонно и не целиком, и аналитическая инверсия там даёт
    # неверное число. В этом случае считаем прямым обходом звёздных суток.
    circumpolar = abs(float(lat)) >= 90.0 - math.degrees(eps)
    dwell = _asc_dwell(arcs, phi, eps) if circumpolar else None

    houses = []
    for k in range(len(arcs)):
        idx = (start_i + k) % len(arcs)
        s, e, code = arcs[idx]
        width = (e - s) % 360.0
        if circumpolar:
            hours = dwell[idx]
            hnote = (None if hours is not None else
                     "асцендент на этой широте в эту дугу не заходит "
                     "(часть эклиптики околополярна) — числа нет, а не ноль")
        else:
            t1 = _lst_when_asc_is(s, phi, eps)
            t2 = _lst_when_asc_is(e, phi, eps)
            if t1 is None or t2 is None:
                hours, hnote = None, "точка эклиптики на этой широте не восходит"
            else:
                hours = ((t2 - t1) % 360.0) / 360.0 * SIDEREAL_DAY_HOURS
                hnote = None
        houses.append({
            "house": k + 1, "code": code, "name": CON88_RU[code],
            "name_lat": CON88_LAT[code], "zodiacal": code in ZODIAC_13,
            "lon_start_deg": round(s, 6), "lon_end_deg": round(e, 6),
            "width_deg": round(width, 6),
            "rise_hours": None if hours is None else round(hours, 5),
            "note": hnote,
        })

    equal = []
    for k in range(12):
        s = (asc + 30.0 * k) % 360.0
        cusp = constellation_of_ecliptic(s, 0.0, jd)
        equal.append({
            "house": k + 1, "lon_start_deg": round(s, 6),
            "lon_end_deg": round((s + 30.0) % 360.0, 6), "width_deg": 30.0,
            "rise_hours": None,
            "cusp_real_constellation": cusp.get("name"),
            "cusp_tropical_sign": tropical_sign(s).get("name"),
        })

    total_h = [h["rise_hours"] for h in houses]
    return {
        "asc_lon_deg": asc, "asc_constellation": houses[0]["name"],
        "asc_tropical_sign": tropical_sign(asc).get("name"),
        "lst_deg": lst, "obliquity_deg": math.degrees(eps),
        "drift_deg": drift_deg(jd),
        "n_houses": len(houses),
        "houses": houses,
        "total_width_deg": round(sum(h["width_deg"] for h in houses), 6),
        # Сумма по дугам, куда асцендент вообще заходит, обязана дать звёздные
        # сутки на ЛЮБОЙ широте: за сутки он где-то да находится всегда.
        "total_rise_hours": round(sum(h for h in total_h if h is not None), 5),
        "n_unreachable": sum(1 for h in total_h if h is None),
        "equal": equal,
        "equal_note": "🟡 равные 30° дома от асцендента — символьная проекция, "
                      "не реальные границы неба",
        "circumpolar": circumpolar,
        "note": "🔵 дома = реальные дуги созвездий вдоль эклиптики; они неравные, "
                "поэтому асцендент проходит их рывками"
                + (" · за полярным кругом часть эклиптики околополярна: в такие "
                   "дуги асцендент не заходит вовсе, у них rise_hours = None"
                   if circumpolar else ""),
    }


