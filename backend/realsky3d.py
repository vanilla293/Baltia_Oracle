def _gmst_deg(jd_ut):
    """Среднее гринвичское звёздное время в градусах (IAU 1982, UT1≈UTC)."""
    d = jd_ut - J2000
    t = d / JULIAN_CENTURY
    return (280.46061837 + 360.98564736629 * d
            + 0.000387933 * t * t - t * t * t / 38710000.0) % 360.0


def _sky_angles(jd_ut):
    """(истинный наклон ε в радианах, истинное звёздное время GAST в градусах).
    ΔT (TT−UT ≈ 70 с в 2026) на нутацию и наклон влияет ниже 0.001″ — опущен."""
    dpsi, deps = nutation(jd_ut)
    eps_true = obliquity_mean_deg(jd_ut) + deps
    gast = (_gmst_deg(jd_ut) + dpsi * math.cos(math.radians(eps_true))) % 360.0
    return math.radians(eps_true), gast


def _asc_lon(jd_ut, geo_lat, geo_lon):
    """Долгота восходящей точки эклиптики (асцендент), градусы.

    🔵 Векторно и без квадрантных ловушек: горизонт и эклиптика — две плоскости,
    их пересечение = zenith × n_ecl; из двух концов берём восточный."""
    eps, gast = _sky_angles(jd_ut)
    lst = math.radians((gast + geo_lon) % 360.0)
    phi = math.radians(geo_lat)
    zen = np.array([math.cos(phi) * math.cos(lst),
                    math.cos(phi) * math.sin(lst), math.sin(phi)])
    n_ecl = np.array([0.0, -math.sin(eps), math.cos(eps)])
    d = np.cross(zen, n_ecl)
    east = np.array([-math.sin(lst), math.cos(lst), 0.0])
    if float(d @ east) < 0.0:
        d = -d
    x = d[0]
    y = d[1] * math.cos(eps) + d[2] * math.sin(eps)
    return math.degrees(math.atan2(y, x)) % 360.0, math.degrees(lst) % 360.0, eps


def _asc_lon_of_lst(lst_deg, phi_rad, eps):
    """Долгота асцендента для массива звёздного времени (градусы) — векторно.

    Тот же приём, что в `_asc_lon`: горизонт и эклиптика пересекаются по прямой
    zenith × n_ecl, из двух её концов берётся ВОСТОЧНЫЙ. Работает на любой
    широте, включая заполярье, где стандартная формула асцендента через
    atan2 отдаёт западный конец (десцендент)."""
    L = np.radians(np.asarray(lst_deg, dtype=np.float64))
    cphi, sphi = math.cos(phi_rad), math.sin(phi_rad)
    zx, zy, zz = cphi * np.cos(L), cphi * np.sin(L), np.full(L.shape, sphi)
    nx, ny, nz = 0.0, -math.sin(eps), math.cos(eps)
    dx = zy * nz - zz * ny
    dy = zz * nx - zx * nz
    dz = zx * ny - zy * nx
    dot_east = dx * (-np.sin(L)) + dy * np.cos(L)
    flip = dot_east < 0.0
    dx = np.where(flip, -dx, dx); dy = np.where(flip, -dy, dy); dz = np.where(flip, -dz, dz)
    y = dy * math.cos(eps) + dz * math.sin(eps)
    return np.degrees(np.arctan2(y, dx)) % 360.0


def _asc_dwell(arcs, phi_rad, eps, n=43200):
    """Сколько времени асцендент проводит в каждой дуге — прямым обходом суток.

    Аналитическая инверсия `_lst_when_asc_is` верна только там, где асцендент
    обходит эклиптику монотонно и целиком. За полярным кругом он этого не
    делает: часть эклиптики он не посещает вовсе, а по остальной идёт рывками
    и возвращается. Тогда единственный честный способ — пройти звёздные сутки
    и посчитать, где асцендент реально был.

    Возвращает список часов по дугам (в порядке `arcs`); дуга, куда асцендент
    не заходит ни разу, получает None — не ноль и не выдуманное число."""
    lst = np.arange(n, dtype=np.float64) * (360.0 / n)
    lam = _asc_lon_of_lst(lst, phi_rad, eps)
    hours = [None] * len(arcs)
    per = SIDEREAL_DAY_HOURS / n
    for i, (s, e, _c) in enumerate(arcs):
        w = (e - s) % 360.0 or 360.0
        cnt = int(np.count_nonzero(((lam - s) % 360.0) < w))
        if cnt:
            hours[i] = cnt * per
    return hours


def _lst_when_asc_is(lam_deg, phi_rad, eps):
    """Звёздное время (градусы), когда асцендент равен долготе lam.
    None — если эта точка эклиптики на данной широте вообще не восходит."""
    lam = math.radians(lam_deg)
    dec = math.asin(math.sin(lam) * math.sin(eps))
    ra = math.atan2(math.sin(lam) * math.cos(eps), math.cos(lam))
    c = -math.tan(phi_rad) * math.tan(dec)
    if not -1.0 <= c <= 1.0:
        return None                            # околополярно: не восходит
    return math.degrees(ra - math.acos(c)) % 360.0


