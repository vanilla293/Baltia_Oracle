def _nth_weekday(y: int, m: int, weekday: int, n: int) -> date:
    """n-й weekday (0=пн) месяца; n=-1 — последний."""
    if n > 0:
        d = date(y, m, 1)
        d += timedelta(days=(weekday - d.weekday()) % 7)
        return d + timedelta(days=7 * (n - 1))
    d = date(y, m, 28)
    while (d + timedelta(days=7)).month == m:
        d += timedelta(days=7)
    return d - timedelta(days=(d.weekday() - weekday) % 7)


def _observed(d: date) -> date:
    """Праздник в субботу → пятница, в воскресенье → понедельник."""
    if d.weekday() == 5:
        return d - timedelta(days=1)
    if d.weekday() == 6:
        return d + timedelta(days=1)
    return d


def us_federal_holidays(year: int) -> set:
    """Федеральные праздники США (с переносом на будни)."""
    h = [date(year, 1, 1),
         _nth_weekday(year, 1, 0, 3),          # MLK
         _nth_weekday(year, 2, 0, 3),          # Washington's Birthday
         _nth_weekday(year, 5, 0, -1),         # Memorial Day
         date(year, 7, 4),
         _nth_weekday(year, 9, 0, 1),          # Labor Day
         _nth_weekday(year, 10, 0, 2),         # Columbus Day
         date(year, 11, 11),                   # Veterans Day
         _nth_weekday(year, 11, 3, 4),         # Thanksgiving
         date(year, 12, 25)]
    if year >= 2021:
        h.append(date(year, 6, 19))            # Juneteenth — с 2021
    return {_observed(x) for x in h}


def eia_days(d0: date, d1: date) -> list:
    """Дни публикации недельного отчёта EIA: среда, а на праздничной неделе
    (праздник пн-ср) — четверг. Правило EIA, аппроксимация 🟡."""
    out = []
    hol = {}
    d = d0
    while d.weekday() != 2:                    # ищем первую среду
        d += timedelta(days=1)
        if d > d1:
            return out
    while d <= d1:
        y = d.year
        if y not in hol:
            hol[y] = us_federal_holidays(y) | us_federal_holidays(y - 1)
        mon = d - timedelta(days=2)
        shift = any((mon + timedelta(days=k)) in hol[y] for k in (0, 1, 2))
        out.append(d + timedelta(days=1) if shift else d)
        d += timedelta(days=7)
    return out


