# ══════════════════════════════════════════════════════════════════════
def macro_days(d0: date, d1: date) -> dict:
    """{'FOMC': [...], 'OPEC': [...], 'EIA': [...]} внутри [d0, d1]."""
    return {
        "FOMC": [date(*t) for t in FOMC if d0 <= date(*t) <= d1],
        "OPEC": [date(*t) for t in OPEC if d0 <= date(*t) <= d1],
        "EIA": eia_days(d0, d1),
    }


def window(days, half: int = 1) -> set:
    """Окно ±half календарных дней вокруг каждого события."""
    out = set()
    for d in days:
        for k in range(-half, half + 1):
            out.add(d + timedelta(days=k))
    return out


def coverage(d0: date, d1: date) -> dict:
    """Честный паспорт покрытия для запрошенного окна."""
    return {
        "FOMC_полное": d0 >= date(2013, 1, 1),
        "FOMC_предварительное_с": FOMC_TENTATIVE_FROM.isoformat(),
        "OPEC_полное": d0 >= OPEC_COVERAGE_START and d1 <= OPEC_COVERAGE_END,
        "OPEC_покрытие": f"{OPEC_COVERAGE_START} … {OPEC_COVERAGE_END}",
        "OPEC_note": OPEC_MISSING_NOTE,
        "EIA_note": "правило «среда, праздничная неделя → четверг» 🟡",
    }


