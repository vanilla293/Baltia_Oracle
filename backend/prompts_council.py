def _extra(extra: str) -> str:
    """Блок разведки FLASH (v5.2): индексы, соседи, курсы — то, чего не было в ленте и ценах каталога."""
    e = (extra or "").strip()
    return f"\n\nДОПОЛНИТЕЛЬНЫЕ ДАННЫЕ (разведка FLASH запросила их перед советом):\n{e}" if e else ""


