def background_user(news_block: str, tickers_meta: list[dict],
                    astro_text: str = "") -> str:
    lst = ", ".join(m["ticker"] for m in tickers_meta)
    parts = [f"Объекты в работе: {lst}", "", "ПОТОК ЗА 2 СУТОК:", news_block]
    if astro_text.strip():
        parts += ["", "АСТРО-ФИЛЬТР (фоновый слой):", astro_text]
    parts += ["", "Дай оценку общего фона: куда клонит и где играют на толпе."]
    return "\n".join(parts)


