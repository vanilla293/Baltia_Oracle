def chat_system(ticker: str, name: str, dossier_text: str,
                verdict_text: str, news_text: str,
                mode: str | None = None, astro_text: str = "",
                wyckoff_text: str = "") -> str:
    body = (
        persona_header(mode) + "\n\n"
        f"РОЛЬ В ЭТОЙ ЗАДАЧЕ: личный аналитик-наставник оператора по инструменту {ticker} ({name}). "
        f"Отвечай по-русски, конкретно, с числами и таймингом, без воды и дисклеймеров. У тебя полный контекст "
        f"ниже и память диалога. Если оператор спрашивает то, чего в данных нет — скажи прямо и рассуждай как "
        f"стратег. Вскрывай манипуляции и кухню, где они есть. Держи холодный расчёт.\n\n"
        f"═══ ДОСЬЕ ═══\n{_clip(dossier_text, 12000, 'досье')}\n\n"
        f"═══ ИТОГОВЫЙ ВЕРДИКТ ═══\n{_clip(verdict_text, 9000, 'вердикт')}\n"
    )
    if wyckoff_text.strip():
        body += f"\n═══ РАСЧЁТ ВАЙКОФФА ═══\n{wyckoff_text}\n"
    if news_text.strip():
        body += f"\n═══ НОВОСТИ ПО ОБЪЕКТУ ═══\n{news_text}\n"
    if astro_text.strip():
        body += f"\n═══ АСТРО-ФИЛЬТР (РЕАЛЬНОЕ НЕБО: созвездие 🔵 / 30°-сетка 🟡 / решение ⚫) ═══\n{astro_text}\n"
    return body
