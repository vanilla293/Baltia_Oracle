def _clip(text: str, limit: int, label: str = "") -> str:
    """Предохранитель промптов: обычные тексты не трогает, аварийные простыни
    (стадия ушла в размышления / гигантский фолбэк) режет с сохранением
    ГОЛОВЫ (постановка) и ХВОСТА (выводы и цифры обычно в конце)."""
    t = (text or "").strip()
    if len(t) <= limit:
        return t
    head = t[: int(limit * 0.35)]
    tail = t[-int(limit * 0.6):]
    cut = len(t) - len(head) - len(tail)
    return (f"{head}\n\n[…{label or 'фрагмент'}: обрезано {cut} симв. "
            f"аварийного объёма — голова и хвост сохранены…]\n\n{tail}")


