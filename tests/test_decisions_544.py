def test_echo_partial_ambush_helpers():
    assert a.echo_of("КУПИТЬ | ПРОДАТЬ | НОВЫЙ_АНАЛИЗ | ЖДЁМ", R0) and a.echo_of("ВОЙТИ/ОТМЕНИТЬ", DL)
    assert not a.echo_of("КУПИТЬ", R0) and not a.echo_of("ВЫЙТИ/ПЕРЕЗАЙТИ", PL), "слово словаря целиком — не эхо"
    assert not a.echo_of("КУПИТЬ/ЗАСАДА", RS), "вход без стороны рядом со стороной — не спор"
    assert a.partial_of("ЗАКРЫТЬ ПОЛОВИНУ") and a.partial_of("частично выйти — прибыль") and not a.partial_of("ЗАКРЫТЬ")
    assert not a.partial_of("ЗАКРЫТЬ — половина хода уже пройдена"), "частичка — только в первом предложении"
    assert a.ambush_of("ЗАСАДА") and a.ambush_of("взвести вход у 99") and a.ambush_of("LIMIT BUY")
    assert not a.ambush_of("КУПИТЬ сейчас — без засады"), "засада во втором предложении — не засада"
    assert a.decision_raw({"choice": ["КУПИТЬ"]}) == "КУПИТЬ" and a.decision_raw({"choice": ["КУПИТЬ", "ЖДЁМ"]}) == ""


@pytest.mark.parametrize("obj,price,want", [
    ({"entry": 99.0, "invalidation": 98.0}, 100.0, "long"),
    ({"entry": 101.0, "invalidation": 102.0, "take": 97.0}, 100.0, "short"),
    ({"invalidation": 98.0, "take": 104.0}, 100.0, "long"),          # без entry — от цены снимка
    ({"invalidation": 102.0}, 100.0, "short"),
    ({"entry": 99.0, "invalidation": 98.0, "take": 97.0}, 100.0, None),   # уровни спорят
    ({"entry": 99.0}, 100.0, None), ({}, 100.0, None), ({"invalidation": 98.0}, None, None), ("ЗАСАДА", 100.0, None),
])
def test_side_by_levels(obj, price, want):
    assert a.side_by_levels(obj, price) == want


def test_review_parse_choice_side_by_levels_and_ambush_without_entry():
    """MissionPilot._parse_choice: вход без стороны — по уровням ответа; засада без entry — None (не вход по рынку)."""
    p = mission.MissionPilot.__new__(mission.MissionPilot)    # метод не читает состояние пилота
    pc = p._parse_choice
    assert pc("ЗАСАДА", False, obj={"entry": 99.0, "invalidation": 98.0, "take": 103.0}, price=100.0) == "КУПИТЬ_СЕЙЧАС"
    assert pc("ЗАСАДА", False, obj={"entry": 101.0, "invalidation": 102.0}, price=100.0) == "ПРОДАТЬ_СЕЙЧАС"
    assert pc("ЗАСАДА", False, obj={"why": "жду отката"}, price=100.0) is None, "без уровней стороны нет"
    assert pc("ЗАСАДА на покупку", False, obj={"invalidation": 98.0}, price=100.0) is None, "засада без entry — не вход"
    assert pc("КУПИТЬ", False, obj={"invalidation": 98.0}, price=100.0) == "КУПИТЬ_СЕЙЧАС", "КУПИТЬ без entry — вход сейчас"
    assert pc("ВОЙТИ", False, obj={"invalidation": 98.0, "take": 104.0}, price=100.0) == "КУПИТЬ_СЕЙЧАС"
    assert pc("ВОЙТИ", False, obj={"invalidation": 98.0, "take": 97.0}, price=100.0) is None, "уровни спорят"
    assert pc("ОТМЕНИТЬ", False, armed=True) == a.REVIEW_CANCEL and pc("ОТМЕНИТЬ", False) is None
    assert pc("ОТМЕНИТЬ", True, "long", armed=True) is None, "в позиции armed не действует — снимать вход нечем"
    assert pc("ПОДТЯНУТЬ ТРОС", True, "long") == "ЖДЁМ" and pc("ЗАКРЫТЬ ПОЛОВИНУ", True, "long") is None
    assert pc("КУПИТЬ | ПРОДАТЬ | НОВЫЙ_АНАЛИЗ | ЖДЁМ", False) is None


def test_unparsed_hints():
    """Подсказка к неразобранному ответу — что именно не так (в строку «ПРОШЛЫЙ ОТВЕТ … НЕ РАЗОБРАН»)."""
    p = mission.MissionPilot.__new__(mission.MissionPilot)
    assert p._unparsed_hint("КУПИТЬ | ПРОДАТЬ | ЖДЁМ", False, None, False) == mission.UNPARSED_ECHO
    assert p._unparsed_hint("ЗАКРЫТЬ ПОЛОВИНУ", True, "long", False) == mission.UNPARSED_PARTIAL
    assert "ЗАКРЫТЬ всё или ДЕРЖАТЬ" in mission.UNPARSED_PARTIAL
    assert p._unparsed_hint("ЗАСАДА", False, None, False) == mission.UNPARSED_SIDELESS
    assert p._unparsed_hint("ХЗ", False, None, False) == mission.UNPARSED_HINT
    assert "entry" in mission.UNPARSED_HINT
