@pytest.mark.parametrize("raw,table,want", CASES, ids=[f"{i}:{c[0][:28]}" for i, c in enumerate(CASES)])
def test_decision_matrix(raw, table, want):
    assert a.decision_of(raw, table) == want


def test_decision_raw_keys_and_types():
    assert a.decision_raw({"Decision": "buy"}) == "buy" and a.decision_raw({"choice": "", "do": "SELL"}) == "SELL"
    assert a.decision_raw({}) == "" and a.decision_raw({"choice": {"x": 1}}) == "" and a.decision_raw(" ВОЙТИ ") == "ВОЙТИ"


def test_no_yes_no_words_and_non_answers_in_vocabulary():
    for w in ("ДА", "YES", "GO"):
        assert w not in a.SYN_ENTER, w
    for w in ("NONE", "PASS"):
        assert w not in a.SYN_WAIT and w not in a.SYN_OUT, w
